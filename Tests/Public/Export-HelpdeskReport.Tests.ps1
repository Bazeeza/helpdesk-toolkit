#Requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.2.0' }
<#
    The four diagnostic commands are mocked with fictitious results: the
    tests never read the computer they run on. Reports are written in
    Pester's TestDrive only, a temporary folder removed after the tests.
#>

BeforeAll {
    $repoRoot = Split-Path -Path (Split-Path -Path $PSScriptRoot -Parent) -Parent
    Import-Module -Name (Join-Path -Path $repoRoot -ChildPath 'HelpdeskToolkit\HelpdeskToolkit.psd1') -Force
}

AfterAll {
    Remove-Module -Name 'HelpdeskToolkit' -ErrorAction SilentlyContinue
}

Describe 'Export-HelpdeskReport' {
    BeforeEach {
        Mock -CommandName 'Get-SystemReport' -ModuleName 'HelpdeskToolkit' -MockWith {
            [pscustomobject]@{ ComputerName = 'PC-EXAMPLE01'; OperatingSystem = 'Microsoft Windows 11 Pro'; Build = '26100'; UptimeText = '1d 2h 3m'; Disks = @() }
        }
        Mock -CommandName 'Test-NetworkHealth' -ModuleName 'HelpdeskToolkit' -MockWith {
            [pscustomobject]@{
                InterfaceAlias = 'Ethernet'; Healthy = $true; FailedStep = $null; Diagnosis = 'Every layer answered.'
                Checks = @([pscustomobject]@{ Step = 1; Name = 'Link'; Status = 'Pass'; Detail = 'Ethernet is Up.' })
            }
        }
        Mock -CommandName 'Get-DiskHealth' -ModuleName 'HelpdeskToolkit' -MockWith {
            [pscustomobject]@{ Status = 'OK'; Issues = @(); Volumes = @(); PhysicalDisks = @(); WarningPercent = 15; CriticalPercent = 5 }
        }
        Mock -CommandName 'Get-InstalledSoftware' -ModuleName 'HelpdeskToolkit' -MockWith {
            [pscustomobject]@{ Name = 'Example <Editor>'; Version = '1.0'; Publisher = 'Example Publisher' }
        }
    }

    Context 'Writing the report' {
        It 'writes one HTML file with the four sections and returns it with PassThru' {
            $file = Export-HelpdeskReport -Path 'TestDrive:\report.html' -PassThru
            $file | Should -BeOfType [System.IO.FileInfo]
            $file.FullName | Should -Be (Join-Path -Path $TestDrive -ChildPath 'report.html')

            $html = Get-Content -LiteralPath $file.FullName -Raw
            foreach ($id in 'system', 'network', 'disk', 'software') {
                $html | Should -Match ('<section id="{0}"' -f $id)
            }
            Should -Invoke -CommandName 'Get-SystemReport' -ModuleName 'HelpdeskToolkit' -Times 1 -Exactly
            Should -Invoke -CommandName 'Test-NetworkHealth' -ModuleName 'HelpdeskToolkit' -Times 1 -Exactly
            Should -Invoke -CommandName 'Get-DiskHealth' -ModuleName 'HelpdeskToolkit' -Times 1 -Exactly
            Should -Invoke -CommandName 'Get-InstalledSoftware' -ModuleName 'HelpdeskToolkit' -Times 1 -Exactly
        }

        It 'returns nothing without PassThru' {
            Export-HelpdeskReport -Path 'TestDrive:\quiet.html' | Should -BeNullOrEmpty
            'TestDrive:\quiet.html' | Should -Exist
        }

        It 'writes UTF-8 without a byte order mark' {
            Export-HelpdeskReport -Path 'TestDrive:\encoding.html'
            $bytes = [System.IO.File]::ReadAllBytes((Join-Path -Path $TestDrive -ChildPath 'encoding.html'))
            ($bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB) | Should -BeFalse
            [System.Text.Encoding]::ASCII.GetString($bytes, 0, 15) | Should -Be '<!DOCTYPE html>'
        }

        It 'encodes the values received from the commands' {
            Export-HelpdeskReport -Path 'TestDrive:\encoded.html'
            $html = Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'encoded.html') -Raw
            $html | Should -Match 'Example &lt;Editor&gt;'
            $html | Should -Not -Match '<Editor>'
        }

        It 'shows the ticket number and the module version' {
            Export-HelpdeskReport -Path 'TestDrive:\ticket.html' -TicketNumber 'INC-0042'
            $html = Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'ticket.html') -Raw
            $html | Should -Match '<dt>Ticket</dt><dd>INC-0042</dd>'
            $version = (Get-Module -Name 'HelpdeskToolkit').Version
            $html | Should -Match ([regex]::Escape("Generated by HelpdeskToolkit $version"))
        }

        It 'refuses a ticket number that is not a simple identifier' {
            { Export-HelpdeskReport -Path 'TestDrive:\bad.html' -TicketNumber '<b>1</b>' } | Should -Throw
            'TestDrive:\bad.html' | Should -Not -Exist
        }
    }

    Context 'Sections' {
        It 'runs only the commands of the sections asked for' {
            Export-HelpdeskReport -Path 'TestDrive:\disk.html' -Section 'Disk'
            Should -Invoke -CommandName 'Get-DiskHealth' -ModuleName 'HelpdeskToolkit' -Times 1 -Exactly
            Should -Invoke -CommandName 'Get-SystemReport' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
            Should -Invoke -CommandName 'Test-NetworkHealth' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
            Should -Invoke -CommandName 'Get-InstalledSoftware' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly

            $html = Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'disk.html') -Raw
            $html | Should -Match '<section id="disk"'
            $html | Should -Not -Match '<section id="system"'
        }

        It 'writes the sections in the fixed order whatever the order asked' {
            Export-HelpdeskReport -Path 'TestDrive:\order.html' -Section 'Software', 'System'
            $html = Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'order.html') -Raw
            $html.IndexOf('<section id="system"') | Should -BeLessThan $html.IndexOf('<section id="software"')
        }

        It 'keeps going when one section fails, and says why in the report' {
            Mock -CommandName 'Test-NetworkHealth' -ModuleName 'HelpdeskToolkit' -MockWith { throw 'No network adapter found.' }

            Export-HelpdeskReport -Path 'TestDrive:\partial.html' -WarningVariable warnings -WarningAction SilentlyContinue
            $html = Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'partial.html') -Raw
            $html | Should -Match '<p class="missing">Not collected: No network adapter found.</p>'
            $html | Should -Match '<section id="disk"'
            @($warnings) | Should -HaveCount 1
            "$($warnings[0])" | Should -Match 'Network section could not be collected'
        }

        It 'treats a non-terminating error of a command as a failed section' {
            Mock -CommandName 'Get-SystemReport' -ModuleName 'HelpdeskToolkit' -MockWith { Write-Error -Message 'cannot read the system information.' }

            Export-HelpdeskReport -Path 'TestDrive:\system-error.html' -Section 'System' -WarningAction SilentlyContinue
            $html = Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'system-error.html') -Raw
            $html | Should -Match 'Not collected: cannot read the system information.'
        }
    }

    Context 'Path and existing files' {
        It 'creates the default file name inside a folder given as Path' {
            $folder = New-Item -Path 'TestDrive:\reports' -ItemType Directory
            $file = Export-HelpdeskReport -Path $folder.FullName -PassThru
            $file.DirectoryName | Should -Be $folder.FullName
            $file.Name | Should -Match ('^HelpdeskReport-{0}-\d{{8}}-\d{{6}}\.html$' -f [regex]::Escape($env:COMPUTERNAME))
        }

        It 'resolves a relative path from the current PowerShell location' {
            Push-Location -Path $TestDrive
            try {
                Export-HelpdeskReport -Path 'relative.html'
            }
            finally {
                Pop-Location
            }
            'TestDrive:\relative.html' | Should -Exist
        }

        It 'does not replace an existing file without Force' {
            Set-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'existing.html') -Value 'keep me'
            Export-HelpdeskReport -Path 'TestDrive:\existing.html' -ErrorVariable failure -ErrorAction SilentlyContinue
            "$($failure[0])" | Should -Match 'already exists'
            $failure[0].CategoryInfo.Category | Should -Be 'ResourceExists'
            (Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'existing.html') -Raw).Trim() | Should -Be 'keep me'
            Should -Invoke -CommandName 'Get-SystemReport' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
        }

        It 'replaces an existing file with Force' {
            Set-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'replace.html') -Value 'old'
            Export-HelpdeskReport -Path 'TestDrive:\replace.html' -Force
            Get-Content -LiteralPath (Join-Path -Path $TestDrive -ChildPath 'replace.html') -Raw | Should -Match '<!DOCTYPE html>'
        }

        It 'reports a missing folder instead of creating it' {
            Export-HelpdeskReport -Path 'TestDrive:\missing\report.html' -ErrorVariable failure -ErrorAction SilentlyContinue
            "$($failure[0])" | Should -Match 'does not exist'
            'TestDrive:\missing' | Should -Not -Exist
        }
    }

    Context 'WhatIf' {
        It 'collects nothing and writes nothing' {
            Export-HelpdeskReport -Path 'TestDrive:\whatif.html' -WhatIf
            'TestDrive:\whatif.html' | Should -Not -Exist
            Should -Invoke -CommandName 'Get-SystemReport' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
            Should -Invoke -CommandName 'Test-NetworkHealth' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
            Should -Invoke -CommandName 'Get-DiskHealth' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
            Should -Invoke -CommandName 'Get-InstalledSoftware' -ModuleName 'HelpdeskToolkit' -Times 0 -Exactly
        }
    }
}
